#!/usr/bin/env node
// Generate TypeScript types from the engine's OpenAPI schema.
//
//   python -m engine.server --openapi app/src/shared/api-schema.json   (from the repo root)
//   npm run gen:api                                                     (from app/)
//
// No dependencies: the engine's schema (Pydantic v2 via FastAPI) uses a small,
// predictable subset of JSON Schema. A Vitest test regenerates the file in
// memory and fails when the committed api-types.ts is stale.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
export const SCHEMA_PATH = join(here, '..', 'src', 'shared', 'api-schema.json')
export const OUT_PATH = join(here, '..', 'src', 'shared', 'api-types.ts')

const HEADER = `// GENERATED by app/scripts/gen-api-types.mjs from api-schema.json. Do not edit.
// Regenerate: python -m engine.server --openapi app/src/shared/api-schema.json && npm run gen:api
/* eslint-disable */
`

const byKey = ([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)

/** JSON Schema → TypeScript type expression. */
export function tsType(schema) {
  if (!schema || typeof schema !== 'object') return 'unknown'
  if (schema.$ref) return schema.$ref.split('/').pop()
  for (const key of ['anyOf', 'oneOf']) {
    if (Array.isArray(schema[key])) return union(schema[key].map(tsType))
  }
  if (Array.isArray(schema.allOf) && schema.allOf.length === 1) return tsType(schema.allOf[0])
  if ('const' in schema) return JSON.stringify(schema.const)
  if (Array.isArray(schema.enum)) return union(schema.enum.map((v) => JSON.stringify(v)))
  if (Array.isArray(schema.type)) return union(schema.type.map((t) => tsType({ ...schema, type: t })))
  switch (schema.type) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array': {
      const item = tsType(schema.items)
      return /[|&]/.test(item) ? `(${item})[]` : `${item}[]`
    }
    case 'object':
      if (schema.properties) return inlineObject(schema)
      if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
        return `Record<string, ${tsType(schema.additionalProperties)}>`
      }
      return 'Record<string, unknown>'
    default:
      return 'unknown'
  }
}

function union(parts) {
  const unique = [...new Set(parts)]
  return unique.length ? unique.join(' | ') : 'never'
}

function field(name, schema, required) {
  const safe = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name)
  return `${safe}${required ? '' : '?'}: ${tsType(schema)}`
}

function inlineObject(schema) {
  const required = new Set(schema.required ?? [])
  const fields = Object.entries(schema.properties ?? {})
    .sort(byKey)
    .map(([name, s]) => field(name, s, required.has(name)))
  return `{ ${fields.join('; ')} }`
}

function namedType(name, schema) {
  const doc = schema.description ? `/** ${schema.description.replace(/\s+/g, ' ').trim()} */\n` : ''
  if (schema.type === 'object' || schema.properties) {
    const required = new Set(schema.required ?? [])
    const fields = Object.entries(schema.properties ?? {})
      .sort(byKey)
      .map(([field_, s]) => `  ${field(field_, s, required.has(field_))}`)
    return `${doc}export interface ${name} {\n${fields.join('\n')}\n}\n`
  }
  return `${doc}export type ${name} = ${tsType(schema)}\n`
}

function responseType(operation) {
  const codes = Object.keys(operation.responses ?? {})
    .filter((c) => /^2\d\d$/.test(c))
    .sort()
  for (const code of codes) {
    const content = operation.responses[code].content
    if (!content) return 'null'
    if (content['application/json']) return tsType(content['application/json'].schema)
    return 'string'
  }
  return 'null'
}

function bodyType(operation) {
  const content = operation.requestBody?.content
  if (!content) return 'never'
  if (content['application/json']) return tsType(content['application/json'].schema)
  return 'FormData'
}

function paramsType(operation, where) {
  const params = (operation.parameters ?? []).filter((p) => p.in === where)
  if (!params.length) return 'never'
  return `{ ${params
    .slice()
    .sort((a, b) => (a.name < b.name ? -1 : 1))
    .map((p) => field(p.name, p.schema, Boolean(p.required)))
    .join('; ')} }`
}

/** The whole api-types.ts file for an OpenAPI schema object. */
export function generate(schema) {
  const out = [HEADER]
  for (const [name, def] of Object.entries(schema.components?.schemas ?? {}).sort(byKey)) {
    if (name === 'HTTPValidationError' || name === 'ValidationError') continue
    out.push(namedType(name, def))
  }
  out.push('/** Every route: `"METHOD /path/{param}"` → its path params, query, body and response. */')
  out.push('export interface ApiRoutes {')
  for (const [path, methods] of Object.entries(schema.paths ?? {}).sort(byKey)) {
    for (const [method, operation] of Object.entries(methods).sort(byKey)) {
      const key = `${method.toUpperCase()} ${path}`
      out.push(
        `  ${JSON.stringify(key)}: {\n` +
          `    params: ${paramsType(operation, 'path')}\n` +
          `    query: ${paramsType(operation, 'query')}\n` +
          `    body: ${bodyType(operation)}\n` +
          `    response: ${responseType(operation)}\n` +
          `  }`,
      )
    }
  }
  out.push('}\n')
  out.push('export type RouteKey = keyof ApiRoutes\n')
  return out.join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const schema = JSON.parse(readFileSync(SCHEMA_PATH, 'utf8'))
  writeFileSync(OUT_PATH, generate(schema), 'utf8')
  console.log(`wrote ${OUT_PATH}`)
}
